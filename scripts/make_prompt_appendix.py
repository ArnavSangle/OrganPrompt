"""Generate the paper's prompt appendix directly from the stored prompt sets.

The caption ablation is not reproducible without the exact prompt text, and 55
prompts (11 classes x 5 levels) is far too much to transcribe into LaTeX by hand
without introducing an error -- which would be especially bad here, since one of
the paper's findings IS a two-word prompt error. So the appendix is generated
from diagnostics/prompts_L*.json, the same files the ablation itself consumed.

Usage:
    python scripts/make_prompt_appendix.py     # -> paper/sections/91_prompts_generated.tex
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))
from src.labels.templates import CLASS_NAMES

DIAG = Path("diagnostics")
OUT = Path("paper/sections/91_prompts_generated.tex")

LEVELS = [
    ("L1", "prompts_L1_class_name.json",       "Class name only"),
    ("L2", "prompts_L2_generic_clinical.json", "Generic clinical caption"),
    ("L3", "prompts_L3_position_only.json",    "Position only, organ name removed"),
    ("L4", "prompts_L4_full_anatomical.json",  "Full anatomical description (used in training)"),
    ("L5", "prompts_L5_adversarial.json",      "Adversarial: L4 with LEFT/RIGHT and top/bottom swapped"),
]

# The L3 lung-right prompt is wrong in both content words. That is a reported
# finding, not a defect to quietly repair, so it is reproduced verbatim and
# flagged in place.
FLAGGED = {("L3", 8): "This prompt is erroneous; see Section 4.2. Reproduced as run."}


def tex_escape(s):
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                 ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"),
                 ("}", r"\}"), ("~", r"\textasciitilde{}"),
                 ("^", r"\textasciicircum{}")]:
        s = s.replace(a, b)
    return s


def main():
    sets = {}
    for key, fname, _ in LEVELS:
        p = DIAG / fname
        if not p.exists():
            sys.exit(f"[prompt_appendix] missing {p}")
        sets[key] = json.loads(p.read_text(encoding="utf-8"))

    out = [
        "% GENERATED by scripts/make_prompt_appendix.py -- do not edit by hand.",
        "% Regenerate after any change to diagnostics/prompts_L*.json.",
        "",
        r"\section{Prompt formulations}",
        r"\label{app:prompts}",
        "",
        "The caption ablation (\\S\\ref{sec:results:ablation}) varies only the text "
        "embedding. All five prompt sets are reproduced below verbatim, generated "
        "directly from the files the ablation consumed.",
        "",
    ]

    for oc in range(len(CLASS_NAMES)):
        name = CLASS_NAMES[oc]
        out.append(r"\subsection*{\texttt{%s}}" % tex_escape(name))
        out.append(r"\begin{description}[leftmargin=3.2em,style=nextline]")
        for key, _, desc in LEVELS:
            text = sets[key].get(str(oc), "")
            item = tex_escape(text)
            note = FLAGGED.get((key, oc))
            if note:
                item += r" \textbf{[%s]}" % tex_escape(note)
            out.append(r"\item[\textbf{%s}] %s" % (key, item))
        out.append(r"\end{description}")
        out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    n = sum(len(v) for v in sets.values())
    print(f"[prompt_appendix] wrote {OUT} ({n} prompts across {len(LEVELS)} levels)")


if __name__ == "__main__":
    main()
